"""Dedicated browser-test API; never change the application's public database schema."""

import argparse
import json
import re
import sys
from pathlib import Path
from uuid import uuid4

FRONTEND = Path(__file__).resolve().parents[1]
BACKEND = FRONTEND.parent / "backend"
sys.path.insert(0, str(BACKEND))

import uvicorn
from alembic import command
from alembic.config import Config
from redis import Redis
from redis.exceptions import RedisError
from pydantic import SecretStr
from sqlalchemy import create_engine, select, text
from sqlalchemy.orm import Session

from app.bootstrap import seed_demo
from app.core.config import Settings
from app.main import create_app
from app.models import Tenant

STATE = FRONTEND / ".playwright-state.json"


def cleanup():
    if not STATE.exists():
        return
    schema = json.loads(STATE.read_text())["schema"]
    if not re.fullmatch(r"e2e_[a-f0-9]{32}", schema):
        raise ValueError("Refusing to clean a schema not generated by this test workflow")
    settings = Settings()
    engine = create_engine(settings.database_url)
    try:
        with engine.begin() as connection:
            exists = connection.scalar(
                text("SELECT EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = :schema)"),
                {"schema": schema},
            )
            if exists:
                connection.execute(text(f'SET LOCAL search_path TO "{schema}"'))
                tenant_ids = list(connection.scalars(select(Tenant.id)))
                connection.execute(text(f'DROP SCHEMA "{schema}" CASCADE'))
                cache = Redis.from_url("redis://127.0.0.1:6379/13", socket_connect_timeout=2)
                try:
                    for tenant_id in tenant_ids:
                        keys = list(cache.scan_iter(match=f"tenant:{tenant_id}:*"))
                        if keys:
                            cache.delete(*keys)
                except RedisError:
                    pass  # These cache entries also have a short TTL.
                finally:
                    cache.close()
        STATE.unlink(missing_ok=True)
    finally:
        engine.dispose()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cleanup", action="store_true")
    args = parser.parse_args()
    if args.cleanup:
        cleanup()
        return
    cleanup()
    settings = Settings()
    schema = "e2e_" + uuid4().hex
    administrative_engine = create_engine(settings.database_url)
    with administrative_engine.begin() as connection:
        connection.execute(text(f'CREATE SCHEMA "{schema}"'))
    administrative_engine.dispose()
    STATE.write_text(json.dumps({"schema": schema}))
    engine = create_engine(settings.database_url, connect_args={"options": "-csearch_path=" + schema})
    try:
        config = Config(str(BACKEND / "alembic.ini"))
        config.set_main_option("script_location", str(BACKEND / "alembic"))
        with engine.begin() as connection:
            config.attributes["connection"] = connection
            command.upgrade(config, "head")
        test_settings = settings.model_copy(update={
            "jwt_secret": SecretStr("browser-test-only-key-" + uuid4().hex),
            "redis_cache_url": "redis://127.0.0.1:6379/13",
            "redis_queue_url": "redis://127.0.0.1:6379/14",
            "queue_name": schema,
        })
        with Session(engine) as session:
            seed_demo(session, test_settings)
        uvicorn.run(create_app(test_settings, engine=engine), host="127.0.0.1", port=8001)
    finally:
        engine.dispose()
        cleanup()


if __name__ == "__main__":
    main()
